/**
 * Concatenate the kit stylesheets into dist/styles.css (no @import left for
 * consumers to resolve). Order is the cascade: base, motion, shell, tabbar,
 * overlays, actions, content, forms, feedback, media, forced-colors.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const ORDER = [
  'base.css',
  'motion.css',
  'shell.css',
  'tabbar.css',
  'overlays.css',
  'actions.css',
  'content.css',
  'forms.css',
  'feedback.css',
  'media.css',
  'forced-colors.css',
];

mkdirSync('dist', { recursive: true });
const parts = ORDER.map((file) => {
  const body = readFileSync(`src/styles/${file}`, 'utf8');
  return `/* ---- ${file} ---- */\n${body}`;
});
const header = `/** GENERATED by @hues/ui (npm run build:css). Do not edit. */\n`;
writeFileSync('dist/styles.css', `${header}${parts.join('\n')}`);
console.log(`@hues/ui styles built from ${ORDER.length} sheets.`);
