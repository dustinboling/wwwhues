/**
 * @hues/tokens build: DTCG JSON -> tokens.css + tokens.d.ts + theme.css.
 *
 * Pinned Style Dictionary 5.8.0 (style-dictionary.com/reference/config,
 * style-dictionary.com/reference/hooks/formats). Custom formats keep every
 * naming and unit decision in this file so output is byte-deterministic:
 * Style Dictionary parses DTCG, resolves {references} (including references
 * embedded in color-mix strings), and reports dangling references as errors.
 *
 * CSS custom property spellings follow the specs exactly (--color-* per the
 * Mina register, --text-*-size per the Thea handoff, --measure-prose).
 * Type role sizes emit as rem (Thea resize rule); locked geometry, spacing,
 * and radius stay px.
 */
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BASE_SOURCES = [
  'tokens/ref.color.json',
  'tokens/ref.space.json',
  'tokens/ref.radius.json',
  'tokens/ref.type.json',
  'tokens/ref.motion.json',
  'tokens/sys.color.json',
  'tokens/sys.type.json',
  'tokens/sys.elevation.json',
  'tokens/comp.tabbar.json',
  'tokens/comp.button.json',
  'tokens/comp.field.json',
  'tokens/comp.player.json',
  'tokens/comp.sheet.json',
  'tokens/comp.card.json',
  'tokens/comp.dialog.json',
  'tokens/comp.groups.json',
  'tokens/comp.shell.json',
  'tokens/comp.density.json',
  'tokens/comp.header.json',
  'tokens/comp.footer.json',
  'tokens/tabbar.lock.json',
];

const THEMES = ['park', 'seeds', 'control', 'play', 'celebrate', 'family'];

const HEADER = `/**
 * GENERATED by @hues/tokens (npm run build:tokens). Do not edit.
 * Source: tokens/*.json (DTCG). Every value traces to its ruling there.
 */
`;

/**
 * DTCG path -> CSS custom property name (without the leading --).
 * @param {string[]} path
 */
function cssVarName(path) {
  const [a, b, ...rest] = path;
  const tail = rest.join('-');
  if (a === 'sys' && b === 'color') return `color-${tail}`;
  if (a === 'sys' && b === 'type') {
    if (rest[0] === 'measure') return `measure-${rest.slice(1).join('-')}`;
    return `text-${tail}`;
  }
  if (a === 'sys' && b === 'elevation') return `elevation-${tail}`;
  if (a === 'ref' && b === 'color') return `ref-color-${tail}`;
  if (a === 'ref' && b === 'space') return `space-${tail}`;
  if (a === 'ref' && b === 'layout') return `layout-${tail}`;
  if (a === 'ref' && b === 'radius') return `radius-${tail}`;
  if (a === 'ref' && b === 'type' && rest[0] === 'family') return `font-${rest.slice(1).join('-')}`;
  if (a === 'ref' && b === 'type' && rest[0] === 'weight') return `weight-${rest.slice(1).join('-')}`;
  if (a === 'ref' && b === 'type' && rest[0] === 'scale') return `type-scale-${rest.slice(1).join('-')}`;
  if (a === 'ref' && b === 'motion') return `motion-${rest.join('-')}`;
  if (a === 'comp') return `${b}-${rest.join('-')}`;
  if (a === 'tabbar' && b === 'lock') return `tabbar-${tail}`;
  if (a === 'pwa') return `pwa-${[b, ...rest].join('-')}`;
  throw new Error(`Unnamed token path: ${path.join('.')}`);
}

/**
 * True for rendered text sizes, which emit as rem per the Thea resize rule
 * (all sizes in rem, unitless leading, no fixed-height text containers).
 * @param {string[]} path
 */
function isTextSize(path) {
  const dotted = path.join('.');
  if (dotted === 'comp.button.label-size') return true;
  if (dotted === 'comp.notice.banner-size') return true;
  return path[0] === 'sys' && path[1] === 'type' && path[path.length - 1] === 'size';
}

/**
 * "61px" -> "3.8125rem" (16px root).
 * @param {string} value
 */
function pxToRem(value) {
  const match = /^([0-9.]+)px$/.exec(value);
  if (!match) throw new Error(`Cannot convert to rem: ${value}`);
  const rem = Number((Number(match[1]) / 16).toFixed(4));
  return `${rem}rem`;
}

/**
 * Original $value (DTCG, may hold {references}) for var() chains.
 * @param {{ original?: { $value?: unknown, value?: unknown } }} token
 */
function originalValue(token) {
  const original = token.original ?? {};
  return original.$value ?? original.value;
}

const REFERENCE_PATTERN = /\{([^}]+)\}/g;

/**
 * CSS declaration value: aliases become var() chains so themes switch at
 * runtime; literals emit directly (text sizes as rem).
 * @param {{ path: string[], $value?: unknown, value?: unknown, original?: { $value?: unknown, value?: unknown } }} token
 */
function cssValue(token) {
  const raw = originalValue(token);
  if (typeof raw === 'string' && raw.includes('{')) {
    return raw.replace(REFERENCE_PATTERN, (_match, ref) => `var(--${cssVarName(String(ref).split('.'))})`);
  }
  const resolved = token.$value ?? token.value;
  if (typeof resolved === 'string' && isTextSize(token.path)) return pxToRem(resolved);
  return String(resolved);
}

/**
 * Resolved literal for tokens.d.ts (references followed, text sizes as rem).
 * @param {{ path: string[], $value?: unknown, value?: unknown }} token
 */
function literalValue(token) {
  const resolved = String(token.$value ?? token.value);
  if (isTextSize(token.path)) return pxToRem(resolved);
  return resolved;
}

StyleDictionary.registerFormat({
  name: 'hues/css-block',
  format: ({ dictionary, options }) => {
    const lines = dictionary.allTokens.map(
      (token) => `  --${cssVarName(token.path)}: ${cssValue(token)};`,
    );
    return `${options.selector} {\n${lines.join('\n')}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'hues/js',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens.map(
      (token) => `  '${cssVarName(token.path)}': '${literalValue(token)}',`,
    );
    return `${HEADER}export const tokens = {\n${entries.join('\n')}};\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'hues/dts',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens.map(
      (token) => `  '${cssVarName(token.path)}': '${literalValue(token)}',`,
    );
    return (
      `${HEADER}/** Resolved token values (references followed). */\n` +
      `export const tokens = {\n${entries.join('\n')}\n} as const;\n\n` +
      `export type TokenName = keyof typeof tokens;\n` +
      `export type ThemeName = ${THEMES.map((t) => `'${t}'`).join(' | ')};\n`
    );
  },
});

/**
 * Tailwind v4 @theme mapping. Runtime variables keep their exact spec
 * spellings; Tailwind-side names take a hues infix so no utility collides
 * with a Tailwind default and no @theme entry is self-referential.
 * Breakpoints are static (Mina 1.3); everything themeable maps with inline
 * so utilities resolve var() at runtime (tailwindcss.com/docs/theme,
 * "Referencing other variables").
 * @param {string} name
 */
function themeEntry(name) {
  if (name.startsWith('color-')) return `  --color-hues-${name.slice('color-'.length)}: var(--${name});`;
  if (name.startsWith('font-')) return `  --font-hues-${name.slice('font-'.length)}: var(--${name});`;
  if (name.startsWith('radius-')) return `  --radius-hues-${name.slice('radius-'.length)}: var(--${name});`;
  if (name.startsWith('elevation-') && name !== 'elevation-flat' && name !== 'elevation-shadow-color') {
    return `  --shadow-hues-${name.slice('elevation-'.length)}: var(--${name});`;
  }
  const sizeMatch = /^text-(.+)-size$/.exec(name);
  if (sizeMatch) return `  --text-hues-${sizeMatch[1]}: var(--${name});`;
  const leadingMatch = /^text-(.+)-leading$/.exec(name);
  if (leadingMatch) return `  --text-hues-${leadingMatch[1]}--line-height: var(--${name});`;
  return null;
}

StyleDictionary.registerFormat({
  name: 'hues/theme',
  format: ({ dictionary }) => {
    const entries = dictionary.allTokens
      .map((token) => themeEntry(cssVarName(token.path)))
      .filter((entry) => entry !== null);
    return (
      `${HEADER}/* Import after tokens.css. Spacing, motion, and component tokens\n` +
      `   stay var() consumers by design (see README); breakpoints are static. */\n` +
      `@theme {\n` +
      `  --breakpoint-tablet: 48rem;\n` +
      `  --breakpoint-desktop: 64rem;\n` +
      `  --breakpoint-wide: 80rem;\n` +
      `}\n\n` +
      `@theme inline {\n${entries.join('\n')}\n}\n`
    );
  },
});

const sd = new StyleDictionary({
  source: BASE_SOURCES,
  platforms: {
    css: {
      buildPath: 'dist/.parts/',
      files: [
        { destination: 'base.css', format: 'hues/css-block', options: { selector: ':root' } },
        { destination: 'tokens.js', format: 'hues/js' },
        { destination: 'tokens.d.ts', format: 'hues/dts' },
        { destination: 'theme.css', format: 'hues/theme' },
      ],
    },
  },
});

await sd.buildAllPlatforms();

for (const theme of THEMES) {
  const themed = await sd.extend({
    source: [...BASE_SOURCES, `tokens/theme.${theme}.json`],
    platforms: {
      css: {
        buildPath: 'dist/.parts/',
        files: [
          {
            destination: `${theme}.css`,
            format: 'hues/css-block',
            options: { selector: `[data-theme="${theme}"]` },
            filter: (token) => token.filePath?.endsWith(`theme.${theme}.json`) === true,
          },
        ],
      },
    },
  });
  await themed.buildAllPlatforms();
}

mkdirSync('dist', { recursive: true });
const parts = ['base.css', ...THEMES.map((t) => `${t}.css`)].map((file) =>
  readFileSync(join('dist', '.parts', file), 'utf8'),
);
writeFileSync(join('dist', 'tokens.css'), `${HEADER}${parts.join('\n')}`);
writeFileSync(join('dist', 'tokens.js'), readFileSync(join('dist', '.parts', 'tokens.js'), 'utf8'));
writeFileSync(join('dist', 'tokens.d.ts'), readFileSync(join('dist', '.parts', 'tokens.d.ts'), 'utf8'));
writeFileSync(join('dist', 'theme.css'), readFileSync(join('dist', '.parts', 'theme.css'), 'utf8'));
rmSync(join('dist', '.parts'), { recursive: true, force: true });
console.log(`@hues/tokens built: tokens.css, tokens.d.ts, theme.css (${THEMES.length} themes).`);
