// Writes the deployed trailing-slash rule set (dist/client/_redirects).
//
// Post-build step of `npm run build:app` (Slice G): Vike prerenders
// directory-shape HTML (help/index.html) and the worker's assets use
// html_handling "drop-trailing-slash", so the canonical slash-less URL
// serves 200 directly — but the asset layer's own html-handling
// redirects are 307s, and the URL contract demands one-hop 301s from
// the trailing-slash variants to the canonical. Static _redirects rules
// are evaluated BEFORE html-handling, so one exact 301 rule per
// prerendered directory gives: /help → 200, /help/ → 301 /help.
//
// Generated from the build output itself (every */index.html dir), never
// hand-maintained: content routes, prerendered-shell SPA routes, and
// /offline are all covered automatically, and a route that stops
// prerendering loses its rule on the next build. Pinned by
// tests/html/deployed-shape.test.ts (exact coverage in both directions).

import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const client = join(root, 'dist', 'client')

function indexDirs(dir) {
  const routes = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (!statSync(full).isDirectory()) continue
    const rel = relative(client, full).split(sep).join('/')
    let hasIndex = false
    try {
      hasIndex = statSync(join(full, 'index.html')).isFile()
    } catch {
      hasIndex = false
    }
    if (hasIndex) routes.push(`/${rel}`)
    routes.push(...indexDirs(full))
  }
  return routes
}

let routes
try {
  routes = indexDirs(client).sort()
} catch (error) {
  console.error(
    `write-spa-redirects: cannot scan dist/client/ (${error instanceof Error ? error.message : error}); run vike build first.`,
  )
  process.exit(1)
}

if (routes.length === 0) {
  console.error('write-spa-redirects: no prerendered index.html dirs found; refusing to write an empty map.')
  process.exit(1)
}

const lines = [
  '# GENERATED by scripts/write-spa-redirects.mjs — do not hand-edit.',
  '# One-hop 301s: trailing-slash variant → canonical slash-less URL.',
]
for (const route of routes) {
  lines.push(`${route}/ ${route} 301`)
}
writeFileSync(join(client, '_redirects'), `${lines.join('\n')}\n`)
console.log(`write-spa-redirects: wrote dist/client/_redirects (${routes.length} rules)`)
